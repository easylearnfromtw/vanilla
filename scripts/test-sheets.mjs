import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";

const code=readFileSync(new URL("../src/sheets/model.ts",import.meta.url),"utf8");
const output=ts.transpileModule(code,{fileName:"model.ts",compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
const issues=(output.diagnostics||[]).filter(x=>x.category===ts.DiagnosticCategory.Error);
assert.equal(issues.length,0,"model.ts should transpile without errors");
const m=await import("data:text/javascript;base64,"+Buffer.from(output.outputText).toString("base64"));
const book=m.emptyWorkbook(),sheet=book.sheets[0];
m.setCell(sheet,"A1","10");
m.setCell(sheet,"A2","20");
m.setCell(sheet,"B1","=SUM(A1:A2)");
m.setCell(sheet,"B2","=AVERAGE(A1:A2)");
m.setCell(sheet,"B3","=ROUND(B2/3,2)");
m.setCell(sheet,"B4","=IF(A2>A1,\"YES\",\"NO\")");
assert.equal(m.displayValue(sheet,"B1"),"30");
assert.equal(m.displayValue(sheet,"B2"),"15");
assert.equal(m.displayValue(sheet,"B3"),"5");
assert.equal(m.displayValue(sheet,"B4"),"YES");
m.setCell(sheet,"C1","=C2");
m.setCell(sheet,"C2","=C1");
assert.equal(m.displayValue(sheet,"C1"),"#CYCLE!");
m.setCell(sheet,"C3","=A1/0");
assert.equal(m.displayValue(sheet,"C3"),"#DIV/0!");
assert.deepEqual(m.rect("A1:B2"),["A1","B1","A2","B2"]);
assert.equal(m.rect("Z200:AA201").length,0);
const rows=m.parseDelimited('Name,Comment\nA,"Hello, ""world"""\n');
assert.deepEqual(rows,[["Name","Comment"],["A",'Hello, "world"']]);
m.setCell(sheet,"D1","@cmd");
assert.match(m.csvForSheet(sheet),/'@cmd/);
assert.equal(m.isWorkbook(book),true);
assert.equal(m.isWorkbook({version:1,title:"bad",sheets:[{id:"x",name:"test",cells:{AA999:{value:"x"}}}]}),false);
console.log("Vanilla Sheets model smoke tests passed");
