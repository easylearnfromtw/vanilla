function row([domain,prompt,completion]){return {domain,prompt:[{role:"user",content:prompt}],completion:[{role:"assistant",content:completion}]};}
export const TRAIN=CASES.map(row);
export const HOLDOUT=EVAL.map(row);
export function audit(){
 const all=[...TRAIN,...HOLDOUT];
 const prompts=new Set();
 for(const record of all){
  const prompt=record.prompt[0].content,answer=record.completion[0].content;
  if(prompts.has(prompt))throw Error("DUPLICATE_PROMPT");
  prompts.add(prompt);
  if(prompt.length<8||answer.length<8||answer.length>5000)throw Error("CASE_LENGTH");
  if(/(?:已幫你部署|保證獲利|我已在背景)/.test(answer))throw Error("UNSUPPORTED_TOOL_OR_GUARANTEE_CLAIM");
 }
 return {train:TRAIN.length,holdout:HOLDOUT.length,domains:[...new Set(all.map(x=>x.domain))].sort()};
}
export function emit(){
 audit();
 const dir=join(ROOT,"generated");
 mkdirSync(dir,{recursive:true});
 for(const [name,records] of [["october-teacher-sft-train.jsonl",TRAIN],["october-teacher-sft-eval.jsonl",HOLDOUT]]){
  writeFileSync(join(dir,name),records.map(({prompt,completion})=>JSON.stringify({prompt,completion})).join("\n")+"\n","utf8");
 }
 return audit();
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===process.argv[1])console.log(JSON.stringify(emit()));
