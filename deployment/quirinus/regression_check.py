"""Fail-closed Quirinus PR risk regression gate. Only aggregate public counts.

Both scan reports must be generated by the trusted base scanner. If aggregate
Critical or High counts increase, block this PR check pending human review.
Never publish finding locations, code, evidence, or an untrusted report field.
"""
from __future__ import annotations

import json
from pathlib import Path
import sys

from autonomous_alert import normalize

_LIMIT = 16 * 1024


def read_report(name: str) -> dict:
    path = Path(name)
    if not path.is_file() or path.stat().st_size > _LIMIT:
        raise ValueError("Missing or oversized report")
    return normalize(json.loads(path.read_text(encoding="utf-8")))


def compare(base: dict, candidate: dict) -> dict:
    base_counts, candidate_counts = base["severityCounts"], candidate["severityCounts"]
    base_severe = (base_counts["Critical"], base_counts["High"])
    next_severe = (candidate_counts["Critical"], candidate_counts["High"])
    # Either category growing requires review. Not every positive delta is a
    # new vulnerability, and decreases do not guarantee a fix.
    increased = any(after > before for before, after in zip(base_severe, next_severe))
    incomplete = base["truncated"] or candidate["truncated"]
    return {
        "blocked": increased or incomplete,
        "reason": "incomplete" if incomplete else ("elevated" if increased else "stable"),
        "criticalBefore": base_severe[0], "criticalAfter": next_severe[0],
        "highBefore": base_severe[1], "highAfter": next_severe[1],
        "fileCountBefore": base["filesScanned"], "fileCountAfter": candidate["filesScanned"],
    }


def render(result: dict) -> str:
    return "\n".join([
        "### Quirinus PR aggregate risk comparison",
        "",
        "Baseline and proposed code were both scanned with a trusted-base, offline scanner.",
        "",
        "| Rule category | Trusted main | Proposed PR |",
        "| --- | ---: | ---: |",
        f"| Critical | {result['criticalBefore']} | {result['criticalAfter']} |",
        f"| High | {result['highBefore']} | {result['highAfter']} |",
        f"| Files | {result['fileCountBefore']} | {result['fileCountAfter']} |",
        "",
        "Result: **{}**. Rule count changes require developer review, not automatic patching.".format(
            "Review required" if result["blocked"] else "No elevated aggregate regression"
        ),
        "No file paths, evidence, private code, credentials or fix queue are published.",
        "",
    ])


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        print("::error::Quirinus comparison setup is incomplete")
        return 2
    try:
        before, after = read_report(argv[1]), read_report(argv[2])
        result = compare(before, after)
        with Path(argv[3]).open("a", encoding="utf-8") as summary:
            summary.write(render(result))
        if result["blocked"]:
            print("::error title=Quirinus aggregate security review::"
                  "Critical or High rule counts rose, or a scan was truncated. "
                  "Owner review required; no exploit was confirmed.")
            return 1
        print("Quirinus PR comparison passed: no increasing Critical/High rule counts.")
        return 0
    except (OSError, ValueError, TypeError, KeyError, UnicodeError, OverflowError):
        print("::error::Quirinus comparison could not validate both sanitized reports.")
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
